/**
 * WheatGuard — Public shared-diagnosis page (/share/{shareToken})
 *
 * The [id] route segment now carries the secure SHARE TOKEN (never the
 * private prediction UUID). Data comes from the public whitelisted endpoint
 * GET /api/v1/share/{token} — no auth, no private fields, and the ML model
 * is never re-run: every value is the stored record the owner sees in-app.
 *
 * Rendered server-side so social crawlers (WhatsApp, Facebook, X) receive
 * real Open Graph / Twitter preview metadata.
 *
 * Section hierarchy mirrors the in-app result page:
 *   Analysed Image → Diagnosis (severity, AI confidence + status) →
 *   Recommended Action → AI Diagnosis Report (Report Type / Generated by /
 *   Problem / Recommendation / Solution) → Top Predictions →
 *   Disease Information → Model Information.
 *
 * Distinct states (§23): invalid/deleted 404, owner-disabled 410, and
 * backend/server errors each show their own message. `cache: "no-store"`
 * guarantees revoked or deleted predictions stop rendering immediately.
 */

import type { Metadata } from "next";
import { headers } from "next/headers";
import Link from "next/link";

import { formatConfidence, getConfidenceTier } from "@/lib/confidence";

export const dynamic = "force-dynamic";

interface TopPrediction {
  rank?: number;
  class_name?: string;
  confidence?: number;
  confidence_percentage?: number;
}

interface DiseaseBrief {
  display_name: string;
  description: string;
  symptoms: string[];
  prevention: string[];
  management: string[];
  severity: string;
  risk_level: string;
  disclaimer: string;
}

interface AiReportBrief {
  title: string;
  problem: string;
  recommendation: string;
  solution: string;
  generated_by: string;
}

interface SharePayload {
  prediction_id: string;
  predicted_class: string;
  confidence: number;
  confidence_pct: number;
  low_confidence: boolean;
  severity: string;
  created_at: string;
  image_url: string | null;
  recommendation: string | null;
  top_predictions: TopPrediction[];
  model_version: string | null;
  disease: DiseaseBrief;
  ai_report: AiReportBrief | null;
}

/** Loader outcome — lets the page tell "no longer available" apart from
 *  "no longer publicly shared" and a genuine backend failure. */
type ShareResult =
  | { kind: "ok"; data: SharePayload }
  | { kind: "disabled" }
  | { kind: "gone" }
  | { kind: "error" };

const API_BASE = process.env.NEXT_PUBLIC_API_URL ?? "http://localhost:8000";

async function loadSharedPrediction(token: string): Promise<ShareResult> {
  try {
    const res = await fetch(`${API_BASE}/api/v1/share/${encodeURIComponent(token)}`, {
      cache: "no-store",
    });
    if (res.status === 410) return { kind: "disabled" };
    if (res.status === 404) return { kind: "gone" };
    if (!res.ok) return { kind: "error" };
    return { kind: "ok", data: (await res.json()) as SharePayload };
  } catch {
    // Backend unreachable → honest server-error state, never a fake report.
    return { kind: "error" };
  }
}

/** "yellow_rust" → "Yellow Rust" (same label rules as the in-app history). */
function displayClass(value: string) {
  const text = value.replace(/_/g, " ").trim();
  if (!text) return "Unknown";
  return text
    .split(" ")
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase())
    .join(" ");
}

function titleCase(value: string) {
  return value.charAt(0).toUpperCase() + value.slice(1).toLowerCase();
}

function formatDate(value: string) {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "—";
  return date.toLocaleDateString("en", {
    year: "numeric",
    month: "short",
    day: "numeric",
  });
}

function severityClasses(severity: string) {
  const v = severity.toLowerCase();
  if (v.includes("critical") || v.includes("severe") || v.includes("high")) {
    return "border-red-100 bg-red-50 text-red-600";
  }
  if (v.includes("moderate") || v.includes("medium")) {
    return "border-amber-100 bg-amber-50 text-amber-700";
  }
  if (v.includes("low") || v.includes("none") || v.includes("healthy")) {
    return "border-emerald-100 bg-emerald-50 text-emerald-700";
  }
  return "border-slate-100 bg-slate-50 text-slate-600";
}

/** Absolute URL of this share page, derived from the incoming request so no
 *  domain is hardcoded (works on localhost, preview and production hosts). */
async function siteOrigin(): Promise<string> {
  const h = await headers();
  const host = h.get("x-forwarded-host") ?? h.get("host") ?? "localhost:3000";
  const proto = h.get("x-forwarded-proto") ?? (host.startsWith("localhost") ? "http" : "https");
  return `${proto}://${host}`;
}

export async function generateMetadata({
  params,
}: {
  params: Promise<{ id: string }>;
}): Promise<Metadata> {
  const { id } = await params;
  const result = await loadSharedPrediction(id);
  const origin = await siteOrigin();
  const url = `${origin}/share/${id}`;

  if (result.kind !== "ok") {
    const title =
      result.kind === "disabled"
        ? "Sharing turned off — WheatGuard AI"
        : result.kind === "error"
          ? "Unable to load report — WheatGuard AI"
          : "Report unavailable — WheatGuard AI";
    return {
      title,
      description:
        result.kind === "disabled"
          ? "This prediction is no longer publicly shared."
          : "This shared prediction is no longer available.",
      openGraph: { title: "WheatGuard AI", url, type: "website" },
    };
  }

  const data = result.data;
  const disease = data.disease.display_name || displayClass(data.predicted_class);
  const pct = formatConfidence(data.confidence); // same stored value as the app
  const healthy = data.predicted_class.toLowerCase().includes("healthy");
  const severityLabel = titleCase(data.severity);
  const description = healthy
    ? `Result: Healthy | AI Confidence: ${pct} | View the complete WheatGuard diagnosis report.`
    : `AI Confidence: ${pct} | Severity: ${severityLabel} | View the complete WheatGuard diagnosis report.`;

  const images = data.image_url
    ? [{ url: data.image_url, width: 1200, height: 630, alt: `Wheat leaf analyzed by WheatGuard — ${disease}` }]
    : undefined;

  return {
    title: `WheatGuard AI Diagnosis — ${disease}`,
    description,
    openGraph: {
      title: `WheatGuard AI Diagnosis — ${disease}`,
      description,
      url,
      type: "website",
      siteName: "WheatGuard AI",
      images,
    },
    twitter: {
      card: images ? "summary_large_image" : "summary",
      title: `WheatGuard AI Diagnosis — ${disease}`,
      description,
      images,
    },
    alternates: { canonical: url },
  };
}

export default async function SharePage({
  params,
}: {
  params: Promise<{ id: string }>;
}) {
  const { id } = await params;
  const result = await loadSharedPrediction(id);

  return (
    <main className="min-h-screen bg-gradient-to-b from-[#F5F9EC] via-white to-[#EAF3DB] px-4 py-10">
      <div className="mx-auto w-full max-w-2xl">
        {/* Brand header */}
        <div className="mb-6 flex items-center justify-center gap-2">
          <span className="material-symbols-outlined text-[28px] text-brand-900">eco</span>
          <span className="text-[20px] font-extrabold tracking-tight text-brand-900">
            WheatGuard <span className="font-semibold text-brand-700">AI</span>
          </span>
        </div>

        {result.kind === "ok" ? (
          <PredictionReport data={result.data} />
        ) : result.kind === "disabled" ? (
          <StateCard
            icon="link_off"
            title="This prediction is no longer publicly shared."
            body="The owner has stopped sharing this diagnosis. The previous link no longer opens it."
          />
        ) : result.kind === "gone" ? (
          <StateCard
            icon="search_off"
            title="This prediction is no longer available."
            body="The link is valid but the result was deleted, or the link was never issued."
          />
        ) : (
          <StateCard
            icon="cloud_off"
            title="Unable to load the shared diagnosis. Please try again."
            body="The analysis service is temporarily unreachable. Retry in a moment."
          />
        )}

        <p className="mt-6 text-center text-[11px] leading-relaxed text-slate-400">
          AI-generated prediction only — always confirm with a plant pathology
          expert before applying treatments.
        </p>
      </div>
    </main>
  );
}

/* ── Full report (mirrors the in-app result page) ───────────────────────── */

function PredictionReport({ data }: { data: SharePayload }) {
  const disease = data.disease.display_name || displayClass(data.predicted_class);
  const pct = formatConfidence(data.confidence);
  const tier = getConfidenceTier(data.confidence, data.predicted_class);
  const healthy = data.predicted_class.toLowerCase().includes("healthy");
  const pctWidth = `${Math.min(Math.max(data.confidence * 100, 2), 100).toFixed(1)}%`;
  // Stored recommendations arrive as one " | "-joined string — render each
  // point as its own line instead of a wall of text.
  const recommendationPoints = (data.recommendation ?? "")
    .split(" | ")
    .map((point) => point.trim())
    .filter(Boolean);
  const report = data.ai_report;

  return (
    <div className="space-y-4">
      {/* 1–6 · Analysed image + diagnosis (disease, severity, confidence) */}
      <section className="overflow-hidden rounded-2xl border border-slate-100 bg-white shadow-xl shadow-emerald-900/5">
        {data.image_url ? (
          // eslint-disable-next-line @next/next/no-img-element
          <img
            src={data.image_url}
            alt={`Analyzed wheat leaf — ${disease}`}
            className="h-64 w-full object-cover"
          />
        ) : (
          <div className="flex h-40 w-full items-center justify-center bg-slate-50">
            <span className="flex items-center gap-2 text-[12px] font-medium text-slate-400">
              <span className="material-symbols-outlined text-[18px]">image_not_supported</span>
              Analyzed image no longer stored
            </span>
          </div>
        )}

        <div className="px-6 pb-7 pt-6">
          <div className="flex flex-wrap items-center justify-between gap-2">
            <div className="text-[11px] font-bold uppercase tracking-[0.14em] text-brand-700">
              AI Prediction
            </div>
            <div className="text-[11px] text-slate-400">
              {formatDate(data.created_at)}
            </div>
          </div>

          <h1 className="mt-1.5 text-[28px] font-extrabold leading-tight text-slate-900">
            {healthy ? "Healthy" : disease}
          </h1>

          {/* Severity */}
          <div className="mt-3 flex items-center justify-between">
            <span className="text-[12px] font-semibold uppercase tracking-wide text-slate-500">
              Severity
            </span>
            <span
              className={`rounded-full border px-3 py-1 text-[12px] font-bold ${severityClasses(healthy ? "none" : data.severity)}`}
            >
              {healthy ? "None" : titleCase(data.severity)}
            </span>
          </div>

          {data.low_confidence && (
            <div className="mt-4 flex items-start gap-2 rounded-xl border border-amber-200 bg-amber-50 px-4 py-3">
              <span className="material-symbols-outlined text-[18px] text-amber-600">
                priority
              </span>
              <p className="text-[12px] leading-relaxed text-amber-800">
                Low-confidence detection — re-scan with a clearer, well-lit
                photo for a more reliable result.
              </p>
            </div>
          )}

          {/* AI Confidence — identical stored value across app, history, share */}
          <div className="mt-5">
            <div className="flex items-end justify-between">
              <span className="text-[12px] font-semibold uppercase tracking-wide text-slate-500">
                AI Confidence
              </span>
              <span className={`text-[18px] font-extrabold ${tier.textClass}`}>{pct}</span>
            </div>
            <div className="mt-1.5 h-2.5 w-full overflow-hidden rounded-full bg-slate-100">
              <div
                className={`h-full rounded-full ${tier.barClass}`}
                style={{ width: pctWidth }}
              />
            </div>
            <div className={`mt-1 text-[11px] font-semibold ${tier.textClass}`}>
              {tier.label}
            </div>
          </div>
        </div>
      </section>

      {/* 8–10 · AI Diagnosis Report (EntryRank-style, stored text only) */}
      {report && (report.problem || report.recommendation || report.solution) && (
        <section className="rounded-2xl border border-slate-100 bg-white px-6 py-6 shadow-lg shadow-emerald-900/5">
          <div className="flex flex-wrap items-start justify-between gap-2">
            <h2 className="flex items-center gap-2 text-[15px] font-bold text-slate-900">
              <span className="material-symbols-outlined text-[20px] text-brand-700">
                smart_toy
              </span>
              {report.title || "AI Diagnosis Report"}
            </h2>
            {report.generated_by && (
              <span className="rounded-full bg-slate-100 px-3 py-1 text-[10px] font-bold uppercase tracking-wide text-slate-500">
                Generated by {report.generated_by}
              </span>
            )}
          </div>

          {report.problem && (
            <div className="mt-4 rounded-xl border border-red-100 bg-red-50/50 px-4 py-3">
              <h3 className="text-[11px] font-bold uppercase tracking-wide text-red-600">
                Problem
              </h3>
              <p className="mt-1 text-[13px] leading-relaxed text-slate-700">{report.problem}</p>
            </div>
          )}

          {report.recommendation && (
            <div className="mt-3 rounded-xl border border-amber-100 bg-amber-50/50 px-4 py-3">
              <h3 className="text-[11px] font-bold uppercase tracking-wide text-amber-700">
                Recommendation
              </h3>
              <p className="mt-1 text-[13px] leading-relaxed text-slate-700">
                {report.recommendation}
              </p>
            </div>
          )}

          {report.solution && (
            <div className="mt-3 rounded-xl border border-emerald-100 bg-emerald-50/50 px-4 py-3">
              <h3 className="text-[11px] font-bold uppercase tracking-wide text-emerald-700">
                Solution
              </h3>
              <p className="mt-1 text-[13px] leading-relaxed text-slate-700">{report.solution}</p>
            </div>
          )}
        </section>
      )}

      {/* 7 · Recommended Action (stored prediction recommendation) */}
      {recommendationPoints.length > 0 && (
        <section className="rounded-2xl border border-emerald-100 bg-emerald-50/60 px-6 py-6 shadow-lg shadow-emerald-900/5">
          <h2 className="flex items-center gap-2 text-[15px] font-bold text-brand-900">
            <span className="material-symbols-outlined text-[20px] text-brand-700">
              lightbulb
            </span>
            Recommended Action
          </h2>

          <ul className="mt-3 space-y-1.5">
            {recommendationPoints.map((point) => (
              <li key={point} className="flex items-start gap-2 text-[13px] leading-relaxed text-slate-700">
                <span className="mt-0.5 text-[15px] text-emerald-700">✓</span>
                {point}
              </li>
            ))}
          </ul>
        </section>
      )}

      {/* 11 · Top Predictions */}
      {data.top_predictions.length > 0 && (
        <section className="rounded-2xl border border-slate-100 bg-white px-6 py-6 shadow-lg shadow-emerald-900/5">
          <h2 className="flex items-center gap-2 text-[15px] font-bold text-slate-900">
            <span className="material-symbols-outlined text-[20px] text-brand-700">
              leaderboard
            </span>
            Top Predictions
          </h2>

          <div className="mt-4 space-y-3">
            {data.top_predictions.slice(0, 3).map((prediction, index) => {
              const raw =
                prediction.confidence_percentage ??
                (prediction.confidence ?? 0) * 100;
              const label = displayClass(prediction.class_name ?? "Unknown");
              const pLabel = `${Math.min(Math.max(raw, 0), 100).toFixed(1)}%`;
              const pTier = getConfidenceTier(prediction.confidence ?? raw / 100, prediction.class_name);

              return (
                <div key={`${prediction.class_name}-${index}`}>
                  <div className="flex items-center justify-between text-[12px]">
                    <span className="font-semibold text-slate-700">
                      {index + 1}. {label}
                    </span>
                    <span className={`font-bold ${pTier.textClass}`}>{pLabel}</span>
                  </div>
                  <div className="mt-1 h-2 w-full overflow-hidden rounded-full bg-slate-100">
                    <div
                      className={`h-full rounded-full ${pTier.barClass}`}
                      style={{ width: `${Math.min(Math.max(raw, 2), 100)}%` }}
                    />
                  </div>
                </div>
              );
            })}
          </div>
        </section>
      )}

      {/* 14 · Disease Information (complete KB details) */}
      {(data.disease.description ||
        data.disease.symptoms.length > 0 ||
        data.disease.management.length > 0 ||
        data.disease.prevention.length > 0) && (
        <section className="rounded-2xl border border-slate-100 bg-white px-6 py-6 shadow-lg shadow-emerald-900/5">
          <h2 className="flex items-center gap-2 text-[15px] font-bold text-slate-900">
            <span className="material-symbols-outlined text-[20px] text-brand-700">
              biotech
            </span>
            Disease Information — {disease}
          </h2>

          {data.disease.description && (
            <p className="mt-3 text-[13px] leading-relaxed text-slate-600">
              {data.disease.description}
            </p>
          )}

          {data.disease.symptoms.length > 0 && (
            <>
              <h3 className="mt-5 text-[13px] font-bold text-slate-900">Symptoms</h3>
              <ul className="mt-2 space-y-1.5">
                {data.disease.symptoms.map((item) => (
                  <li key={item} className="flex items-start gap-2 text-[13px] leading-relaxed text-slate-600">
                    <span className="mt-0.5 text-[15px] text-emerald-600">•</span>
                    {item}
                  </li>
                ))}
              </ul>
            </>
          )}

          {data.disease.management.length > 0 && (
            <>
              <h3 className="mt-5 text-[13px] font-bold text-slate-900">Management</h3>
              <ul className="mt-2 space-y-1.5">
                {data.disease.management.map((item) => (
                  <li key={item} className="flex items-start gap-2 text-[13px] leading-relaxed text-slate-700">
                    <span className="mt-0.5 text-[15px] text-emerald-700">✓</span>
                    {item}
                  </li>
                ))}
              </ul>
            </>
          )}

          {data.disease.prevention.length > 0 && (
            <>
              <h3 className="mt-5 text-[13px] font-bold text-slate-900">Prevention</h3>
              <ul className="mt-2 space-y-1.5">
                {data.disease.prevention.map((item) => (
                  <li key={item} className="flex items-start gap-2 text-[13px] leading-relaxed text-slate-600">
                    <span className="mt-0.5 text-[15px] text-emerald-600">•</span>
                    {item}
                  </li>
                ))}
              </ul>
            </>
          )}

          {data.disease.disclaimer && (
            <div className="mt-5 rounded-xl border border-amber-200 bg-amber-50 px-4 py-3">
              <p className="text-[12px] leading-relaxed text-amber-800">
                {data.disease.disclaimer}
              </p>
            </div>
          )}
        </section>
      )}

      {/* Model Information */}
      <section className="rounded-2xl border border-slate-100 bg-white px-6 py-5 shadow-lg shadow-emerald-900/5">
        <h2 className="flex items-center gap-2 text-[15px] font-bold text-slate-900">
          <span className="material-symbols-outlined text-[20px] text-brand-700">
            memory
          </span>
          Model Information
        </h2>
        <div className="mt-3 grid grid-cols-2 gap-3 text-[12px]">
          <div className="rounded-xl bg-slate-50 px-4 py-3">
            <div className="font-semibold uppercase tracking-wide text-slate-400">Model Version</div>
            <div className="mt-1 font-bold text-slate-800">
              {data.model_version ? `v${data.model_version}` : "—"}
            </div>
          </div>
          <div className="rounded-xl bg-slate-50 px-4 py-3">
            <div className="font-semibold uppercase tracking-wide text-slate-400">Confidence Level</div>
            <div className={`mt-1 font-bold ${tier.textClass}`}>
              {pct} · {tier.label}
            </div>
          </div>
        </div>
      </section>

      <Link
        href="/"
        className="flex w-full items-center justify-center gap-2 rounded-xl bg-brand-900 px-5 py-3 text-[14px] font-bold text-white transition hover:bg-brand-700"
      >
        <span className="material-symbols-outlined text-[18px]">monitoring</span>
        Analyze your own wheat leaf with WheatGuard
      </Link>
    </div>
  );
}

